CREATE OR REPLACE FUNCTION create_sale(
  p_items jsonb,
  p_discount numeric DEFAULT 0,
  p_payment_method text DEFAULT 'cash'
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_sale_id uuid;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2);
  v_total numeric(12,2);
  v_item jsonb;
  v_product products%ROWTYPE;
  v_quantity integer;
  v_line_total numeric(12,2);
  v_invoice text;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin', 'cashier')) THEN
    RAISE EXCEPTION 'Not authorized';
  END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Cart is empty';
  END IF;
  IF p_payment_method NOT IN ('cash', 'card', 'mobile') THEN
    RAISE EXCEPTION 'Invalid payment method';
  END IF;
  v_discount := round(COALESCE(p_discount, 0), 2);
  IF v_discount < 0 OR v_discount > 100000 THEN
    RAISE EXCEPTION 'Invalid discount';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_quantity := (v_item->>'quantity')::integer;
    IF v_quantity IS NULL OR v_quantity < 1 OR v_quantity > 1000 THEN
      RAISE EXCEPTION 'Invalid quantity';
    END IF;
    SELECT * INTO v_product FROM products WHERE id = (v_item->>'product_id')::uuid AND is_active = true FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product unavailable';
    END IF;
    IF v_product.stock < v_quantity THEN
      RAISE EXCEPTION 'Insufficient stock';
    END IF;
    v_line_total := round(v_product.price * v_quantity, 2);
    v_subtotal := v_subtotal + v_line_total;
  END LOOP;

  IF v_discount > v_subtotal THEN
    v_discount := v_subtotal;
  END IF;
  v_total := round(v_subtotal - v_discount, 2);
  v_invoice := 'INV-' || to_char(now(), 'YYYYMMDD') || '-' || nextval('invoice_number_seq');

  INSERT INTO sales (invoice_number, subtotal, discount, total, payment_method)
  VALUES (v_invoice, v_subtotal, v_discount, v_total, p_payment_method)
  RETURNING id INTO v_sale_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_quantity := (v_item->>'quantity')::integer;
    SELECT * INTO v_product FROM products WHERE id = (v_item->>'product_id')::uuid FOR UPDATE;
    v_line_total := round(v_product.price * v_quantity, 2);
    INSERT INTO sale_items (sale_id, product_id, product_name, quantity, unit_price, line_total)
    VALUES (v_sale_id, v_product.id, v_product.name, v_quantity, v_product.price, v_line_total);
    UPDATE products SET stock = stock - v_quantity, updated_at = now() WHERE id = v_product.id;
    INSERT INTO stock_movements (product_id, change_type, quantity, note)
    VALUES (v_product.id, 'sale', -v_quantity, v_invoice);
  END LOOP;
  RETURN v_sale_id;
END;
$$;
REVOKE ALL ON FUNCTION create_sale(jsonb, numeric, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION create_sale(jsonb, numeric, text) TO authenticated;

CREATE OR REPLACE FUNCTION adjust_product_stock(p_product_id uuid, p_quantity integer, p_change_type text, p_note text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_product products%ROWTYPE;
BEGIN
  IF NOT is_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF p_quantity = 0 OR p_quantity IS NULL OR p_change_type NOT IN ('purchase', 'adjustment') THEN RAISE EXCEPTION 'Invalid stock change'; END IF;
  SELECT * INTO v_product FROM products WHERE id = p_product_id FOR UPDATE;
  IF NOT FOUND OR v_product.stock + p_quantity < 0 THEN RAISE EXCEPTION 'Invalid stock change'; END IF;
  UPDATE products SET stock = stock + p_quantity, updated_at = now() WHERE id = p_product_id;
  INSERT INTO stock_movements (product_id, changed_by, change_type, quantity, note)
  VALUES (p_product_id, auth.uid(), p_change_type, p_quantity, NULLIF(trim(p_note), ''));
END;
$$;
REVOKE ALL ON FUNCTION adjust_product_stock(uuid, integer, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION adjust_product_stock(uuid, integer, text, text) TO authenticated;

GRANT USAGE ON SEQUENCE invoice_number_seq TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON sales FROM authenticated;
REVOKE INSERT, UPDATE, DELETE ON sale_items FROM authenticated;
REVOKE UPDATE ON profiles FROM authenticated;
